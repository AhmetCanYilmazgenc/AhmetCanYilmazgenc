def _poly(coords):
    p = Polygon(coords)
    if not p.is_valid:
        p = p.buffer(0)
    return p


def keyframe_geoms(key, island_lookup):
    """(core, vassal) shapely geometrileri (boylam/enlem).

    island_lookup(lon, lat) -> o noktayı içeren ada çokgeni (kara verisinden).
    """
    kf = KEYFRAMES[key]
    year = kf["year"]
    core = unary_union([_poly(c) for c in kf["core"]])
    for s in kf.get("sub", []):
        core = core.difference(_poly(s))
    vassal = unary_union([_poly(c) for c in kf.get("vassal", [])]) if kf.get("vassal") else Polygon()

    add, rem = [], []
    for name, lon, lat, y0, y1 in ISLANDS:
        isl = island_lookup(lon, lat)
        if isl is None:
            continue
        if y0 <= year < y1:
            add.append(isl.buffer(0.04))
        else:
            rem.append(isl.buffer(0.015))
    if rem:
        r = unary_union(rem)
        core = core.difference(r)
        vassal = vassal.difference(r)
    if add:
        core = unary_union([core] + add)
    vassal = vassal.difference(core)
    return core, vassal
